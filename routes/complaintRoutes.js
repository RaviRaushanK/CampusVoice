const router = require("express").Router();
const { rateLimit } = require("express-rate-limit");
const { protect } = require("../middleware/authMiddleware");
const { requireRole } = require("../middleware/roleMiddleware");
const controller = require("../controllers/complaintController");
const student = requireRole("STUDENT"), handler = requireRole("FACULTY", "HOD", "PRINCIPAL");
const limiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, keyGenerator: req => String(req.user._id), standardHeaders: "draft-8", legacyHeaders: false, message: { success: false, message: "Too many complaint submissions or escalation requests. Please try again later." } });
router.use((req, res, next) => { res.set("Cache-Control", "no-store"); next(); }, protect);
router.get("/options", student, controller.options);
router.post("/", student, limiter, require("../middleware/complaintUpload"), controller.create);
router.get("/mine", student, controller.list("mine"));
router.get("/inbox", handler, controller.list("inbox"));
router.get("/:id/attachments/:attachmentId", controller.attachment);
router.get("/:id", controller.get);
router.post("/:id/escalation-request", student, limiter, controller.act("escalation-request"));
router.post("/:id/close", student, controller.act("close"));
for (const kind of ["acknowledge", "start", "escalate", "resolve"]) router.post(`/:id/${kind}`, handler, controller.act(kind));
router.patch("/:id/priority", handler, controller.act("priority"));
module.exports = router;
